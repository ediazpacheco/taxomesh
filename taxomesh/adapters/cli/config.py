"""How the command line reads its configuration and builds its service.

:func:`build` finds the path of ``taxomesh.toml``, lets ``TaxomeshService`` build the repository
that the file names, and returns a :class:`BuildResult` with the service and the facts that the
``--verbose`` block prints.

``CONFIG_KEYS`` and :func:`dump_config` serve ``--show-config``. That option prints the repository
configuration that ``taxomesh._config`` finds, the defaults included, and builds no repository and
no service.
"""

import os
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Final

from taxomesh import TaxomeshService
from taxomesh._config import SUPPORTED_REPO_TYPES, config_file, effective_config
from taxomesh.adapters.repositories.django_repository import (
    DEFAULT_DJANGO_USING,
    DJANGO_REPO_TYPE,
    django_import_error,
)
from taxomesh.adapters.repositories.json_repository import DEFAULT_JSON_PATH
from taxomesh.adapters.repositories.yaml_repository import DEFAULT_YAML_PATH, YAML_REPO_TYPE
from taxomesh.exceptions import TaxomeshConfigError, TaxomeshRepositoryError

# The names of the supported TOML settings, as dotted paths. dump_config reads its key names here.
CONFIG_KEYS: Final[list[str]] = ["repository.type", "repository.path", "repository.using", "taxomesh.name"]

# The control characters that a TOML basic string writes by a short name.
_TOML_SHORT_ESCAPES: Final[dict[str, str]] = {"\b": "\\b", "\t": "\\t", "\n": "\\n", "\f": "\\f", "\r": "\\r"}


def _toml_string(value: str) -> str:
    """Return ``value`` as a TOML basic string, which ``tomllib`` reads back as the same text.

    ``\\`` and ``"`` are escaped, a control character by its short name or as ``\\uXXXX``, and every
    other character, one outside the Basic Multilingual Plane included, is written as it is.
    """
    out = []
    for char in value:
        if char in ('"', "\\"):
            out.append("\\" + char)
        elif char in _TOML_SHORT_ESCAPES:
            out.append(_TOML_SHORT_ESCAPES[char])
        elif char < " " or char == "\x7f":
            out.append(f"\\u{ord(char):04X}")
        else:
            out.append(char)
    return '"' + "".join(out) + '"'


def dump_config(repo_type: str, repo_detail: str, name: str | None = None) -> str:
    """Return the effective configuration as an annotated TOML string.

    The output is valid TOML, which ``tomllib.loads()`` reads. Above each key, comments say what
    the key controls, the values that it accepts and its default. The key names come from
    ``CONFIG_KEYS``, so this function holds no key name as a literal.

    Args:
        repo_type: The repository type that the configuration selects, such as ``"yaml"``,
            ``"json"`` or ``"django"``.
        repo_detail: The path of the file for ``yaml`` and ``json``, or the database alias for
            ``django``.
        name: The ``[taxomesh] name`` that the configuration declares, or ``None``. A ``[taxomesh]``
            section with the name is printed only when there is one.

    Returns:
        The TOML text, which ends with a newline.
    """
    (section, type_key), (_, path_key), (_, using_key), (name_section, name_key) = (k.split(".") for k in CONFIG_KEYS)
    accepted = '", "'.join(SUPPORTED_REPO_TYPES)
    if repo_type == DJANGO_REPO_TYPE:
        detail_comment = (
            f'# The Django database alias: a key of the DATABASES setting.\n# Default: "{DEFAULT_DJANGO_USING}"\n'
        )
        detail_line = f"{using_key} = {_toml_string(repo_detail)}\n"
    else:
        detail_comment = (
            f'# The path of the data file.\n# Default: "{DEFAULT_YAML_PATH}" (yaml) or "{DEFAULT_JSON_PATH}" (json)\n'
        )
        detail_line = f"{path_key} = {_toml_string(repo_detail)}\n"
    name_block = ""
    if name is not None:
        name_block = (
            f"[{name_section}]\n"
            "\n"
            "# The name of this configuration, reported as svc.info.config_name.\n"
            f"{name_key} = {_toml_string(name)}\n"
            "\n"
        )
    return (
        "# The taxomesh configuration in effect\n"
        "# Generated by: taxomesh --show-config\n"
        "# To write a config file, redirect this output to a new file: taxomesh --show-config > taxomesh.toml.new\n"
        "# Never redirect it to the config file in use: the shell empties that file before taxomesh reads it.\n"
        "\n" + name_block + f"[{section}]\n"
        "\n"
        f"# The storage backend.\n"
        f'# Accepted values: "{accepted}"\n'
        f'# Default: "{YAML_REPO_TYPE}"\n'
        f"{type_key} = {_toml_string(repo_type)}\n"
        "\n" + detail_comment + detail_line
    )


@dataclass
class BuildResult:
    """What :func:`build` returns: the service and the config file.

    A command uses the service. The ``--verbose`` block prints the repository of the service and
    the other two fields.

    Attributes:
        service: The service, built from the configuration.
        config_file_path: The absolute path of the config file. The file need not exist.
        config_file_exists: ``True`` if the file at ``config_file_path`` existed when
            :func:`build` ran; ``False`` otherwise.
    """

    service: TaxomeshService
    config_file_path: Path
    config_file_exists: bool


def _set_up_django(config_file_path: Path) -> None:
    """Set Django up when the file names the Django repository and ``DJANGO_SETTINGS_MODULE`` is set.

    The command is the entry point of its process, so it sets Django up; the library's service
    never does.

    Raises:
        TaxomeshConfigError: If the config file cannot be read or parsed.
        TaxomeshRepositoryError: If Django, or its settings module, cannot be imported.
    """
    repo_type, _, _ = effective_config(config_file_path)
    if repo_type != DJANGO_REPO_TYPE or not os.environ.get("DJANGO_SETTINGS_MODULE"):
        return
    try:
        import django  # noqa: PLC0415

        django.setup()
    except ImportError as exc:
        raise django_import_error(exc) from exc


def build(config_path: Path | None = None) -> BuildResult:
    """Find ``taxomesh.toml``, build the service that it configures, and return both.

    ``TaxomeshService`` builds the repository. On a configuration error or a repository error,
    this function prints the message to stderr and exits with status 1.

    Args:
        config_path: The path of the config file. When ``None``, ``taxomesh.toml`` in the working
            directory.

    Returns:
        The service, the absolute path of the config file, and whether that file exists.
    """
    resolved = config_file(config_path).resolve()
    config_file_exists = resolved.exists()
    try:
        _set_up_django(resolved)
        svc = TaxomeshService(config_path=resolved)
    except (TaxomeshConfigError, TaxomeshRepositoryError) as exc:
        print(f"{exc}", file=sys.stderr)
        sys.exit(1)
    return BuildResult(service=svc, config_file_path=resolved, config_file_exists=config_file_exists)
